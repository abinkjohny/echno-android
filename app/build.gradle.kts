// The dev flavor may talk plain HTTP, but only to the hosts it is configured for: the emulator's
// alias for this computer plus whatever host local.properties points the API and Keycloak at.
// Generating the file keeps that list in step with the overrides instead of hard-coding it.
abstract class GenerateDevNetworkSecurityConfig : DefaultTask() {
    @get:Input
    abstract val cleartextHosts: SetProperty<String>

    @get:OutputDirectory
    abstract val outputDirectory: DirectoryProperty

    @TaskAction
    fun generate() {
        val domains =
            cleartextHosts.get().sorted().joinToString("\n") { host ->
                """        <domain includeSubdomains="false">$host</domain>"""
            }
        val file = outputDirectory.file("xml/network_security_config.xml").get().asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |<?xml version="1.0" encoding="utf-8"?>
            |<!-- Generated by :app:$name. Dev only: plain HTTP to the configured local hosts. -->
            |<network-security-config>
            |    <base-config cleartextTrafficPermitted="false" />
            |    <domain-config cleartextTrafficPermitted="true">
            |$domains
            |    </domain-config>
            |</network-security-config>
            |
            """.trimMargin()
        )
    }
}

val devCleartextHosts =
    setOf("10.0.2.2", "localhost") +
        listOf(
            local("echno.dev.apiBaseUrl", "http://10.0.2.2:8080/"),
            local("echno.dev.authIssuer", "http://10.0.2.2:8180/realms/echno-realm")
        ).mapNotNull { URI(it).host }

androidComponents {
    onVariants { variant ->
        // Each build has its own application id (org.echno.dev, org.echno.staging, org.echno), so each
        // gets its own sign-in redirect and Android never asks which installed app should finish a login.
        // AppAuth's redirect activity registers for the appAuthRedirectScheme placeholder.
        variant.manifestPlaceholders.put("appAuthRedirectScheme", variant.applicationId)
        variant.buildConfigFields?.put(
            "AUTH_REDIRECT_URI",
            variant.applicationId.map { BuildConfigField("String", "\"$it:/oauth2redirect\"", null) }
        )
    }
    onVariants(selector().withFlavor("environment" to "dev")) { variant ->
        val task =
            tasks.register<GenerateDevNetworkSecurityConfig>(
                "generate${variant.name.replaceFirstChar(Char::uppercase)}NetworkSecurityConfig"
            ) {
                cleartextHosts.set(devCleartextHosts)
            }
        variant.sources.res?.addGeneratedSourceDirectory(task, GenerateDevNetworkSecurityConfig::outputDirectory)
    }
}

